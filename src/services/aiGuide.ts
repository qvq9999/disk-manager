// ============ AI 助手的页面引导 ============
//
// 为什么按页面走而不是一套通用问题：
// 用户在「硬件信息」页想问的多半是「这配置怎么样」，在「空间分析」页想问的是
// 「这一层哪个能删」。给所有人同一组问题，等于把最贴合当下场景的那一问藏起来了。
//
// 选词规则（有讲究）：
// 1. **至少一两项能命中本地问答库**（`knowledge.ts` 的 keys），这样即使没配置 AI、
//    或额度用尽，点下去也能立刻得到答案，而不是一句「配置后才能答」。
// 2. **其余项是需要结合页面数据的**（配置、当前目录、扫描结果），这正是 AI 的价值所在。
// 3. 单条不超过 14 个字，避免 chip 换行后高度参差。

import type { Page } from '../types'

export interface PageGuide {
  /** 空态标题：这一页最可能想问什么 */
  title: string
  /** 3~4 个可点问题 */
  chips: string[]
}

const GUIDE: Record<Page, PageGuide> = {
  hardware: {
    title: '想看懂这台机器的配置，或者判断该不该升级，都可以问我',
    chips: ['我的配置算什么水平', '哪个硬件最该升级', '内存频率为什么显示这么低'],
  },
  overview: {
    title: '分区快满了、硬盘健康度看不明白，都可以问我',
    chips: ['哪个盘最该清理', 'C 盘空间对不上是什么原因', 'SSD 健康度怎么看'],
  },
  drive: {
    title: '拿不准某个目录能不能删，直接问我就行',
    chips: ['这一层哪些能删', '扫描结果比实际小怎么办', '目录点不开是为什么'],
  },
  clean: {
    title: '哪些项目该清、会不会误删，可以先问清楚再动手',
    chips: ['为什么有些项目默认不勾', '清理会不会删掉配置文件', '安装包清理和卸载有什么区别'],
  },
  uninstall: {
    title: '卸载后残留要不要清、怎么清干净，都可以问',
    chips: ['卸载残留要不要清理', '卸载和强制卸载有什么区别', '商店应用卸不干净怎么办'],
  },
  settings: {
    title: 'AI 配置、开机自启与数据隐私相关的问题，都可以问',
    chips: ['AI 怎么配置', '数据会上传吗', '为什么需要管理员权限'],
  },
  ai: {
    title: '这里用来配置 AI 助手，有拿不准的直接问',
    chips: ['内置额度和自己的 Key 有什么区别', 'AI 判断准不准', '数据会上传吗'],
  },
}

export function guideFor(page: Page): PageGuide {
  return GUIDE[page] ?? GUIDE.hardware
}
