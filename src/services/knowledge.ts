/**
 * 本地匹配。返回 null 表示本地答不了，交给模型。
 *
 * 打分用「命中关键词的字符数之和」，阈值 3：
 * 单字命中（如「删」）不算数，避免把不相关的问题硬塞一个答案。
 */
export function answerLocally(q: string): string | null {
  const s = q.toLowerCase().replace(/\s+/g, '')
  if (s.length < 2) return null

  let bestScore = 0
  let best: string | null = null
  for (const e of FAQ) {
    let score = 0
    for (const k of e.keys) {
      if (s.includes(k)) score += k.length
    }
    if (score > bestScore) {
      bestScore = score
      best = e.a
    }
  }
  return bestScore >= 3 ? best : null
}
